#!/usr/bin/env bash
# Installs Path of Building for the current user, using the native Linux engine.
#
# Usage:
#   linux/install.sh              install (or reinstall) to ~/.local/opt/path-of-building
#   linux/install.sh --uninstall  remove the program, launcher and menu entry (builds/settings are kept)
#
# Environment:
#   POB_PREFIX   install directory          (default: ~/.local/opt/path-of-building)
#   POB_BRANCH   branch of the fork the updater follows (default: master)
#
# The layout mirrors a Windows install: program (src/) and runtime files side by side in one folder.
# Builds and settings are stored in ${XDG_DATA_HOME:-~/.local/share}/Path of Building/.
set -euo pipefail

POB_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PREFIX="${POB_PREFIX:-$HOME/.local/opt/path-of-building}"
BRANCH="${POB_BRANCH:-master}"
BIN_DIR="$HOME/.local/bin"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
DESKTOP_FILE="$DATA_HOME/applications/path-of-building.desktop"
ICON_FILE="$DATA_HOME/icons/hicolor/256x256/apps/path-of-building.png"
WRAPPER="$BIN_DIR/path-of-building"

if [[ "${1:-}" == "--uninstall" ]]; then
	rm -rf -- "$PREFIX"
	rm -f -- "$WRAPPER" "$DESKTOP_FILE" "$ICON_FILE"
	command -v update-desktop-database >/dev/null && update-desktop-database "$DATA_HOME/applications" || true
	echo "Uninstalled. Your builds and settings in '$DATA_HOME/Path of Building' were left in place."
	exit 0
fi

echo "==> Installing to $PREFIX"
"$POB_ROOT/linux/stage-app.sh" "$PREFIX" "$BRANCH"

echo "==> Creating launcher $WRAPPER"
mkdir -p "$BIN_DIR"
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# Path of Building (native Linux) launcher, generated by linux/install.sh
export LUA_PATH="$PREFIX/lua/?.lua;$PREFIX/lua/?/init.lua;;"
exec "$PREFIX/PathOfBuilding" "$PREFIX/Launch.lua" "\$@"
EOF
chmod +x "$WRAPPER"

echo "==> Adding menu entry"
mkdir -p "$(dirname "$DESKTOP_FILE")" "$(dirname "$ICON_FILE")"
cp "$POB_ROOT/linux/path-of-building.png" "$ICON_FILE"
cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=Path of Building
GenericName=Path of Exile Build Planner
Comment=Offline build planner for Path of Exile
Exec="$WRAPPER" %u
Icon=path-of-building
Terminal=false
Categories=Game;Utility;
StartupWMClass=Path of Building
MimeType=x-scheme-handler/pob;
EOF
command -v update-desktop-database >/dev/null && update-desktop-database "$DATA_HOME/applications" || true
command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -q -t "$DATA_HOME/icons/hicolor" || true

echo "Done. Launch 'Path of Building' from your app menu, or run: $WRAPPER"
case ":$PATH:" in *":$BIN_DIR:"*) ;; *) echo "note: $BIN_DIR is not on your PATH" ;; esac
